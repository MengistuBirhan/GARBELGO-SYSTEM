/*
# Construction Materials Sales & Dispatch System — Schema

A single-tenant (no auth) system for selling and dispatching construction
materials (sand, gravel, stone). Cashiers record sales, generate printable
invoices, and issue gate passes for truck dispatch. Credit customers carry
balances tracked in a ledger.

## Tables

1. `materials` — the catalog of sellable materials
   - id (uuid pk)
   - name_am (text, Amharic name, e.g. አሸዋ)
   - name_en (text, English name, e.g. Sand)
   - subtype (text, optional subtype/grade e.g. 00, #1, Cobble)
   - unit (text, measurement unit: m³, truck_load, ton)
   - unit_price (numeric, current selling price per unit, ETB)
   - stock_quantity (numeric, current on-hand quantity in `unit`)
   - low_stock_threshold (numeric, alert threshold)
   - created_at (timestamptz)

2. `customers` — credit customers (contractors/companies)
   - id (uuid pk)
   - name (text, customer/company name)
   - phone (text, optional)
   - credit_limit (numeric, ETB, max allowed outstanding debt)
   - created_at (timestamptz)

3. `sales` — each sale / invoice
   - id (uuid pk)
   - invoice_number (text, unique human-readable, e.g. INV-000123)
   - customer_name (text, walk-in or credit customer name)
   - customer_id (uuid, nullable FK to customers, set when on credit)
   - material_id (uuid FK to materials)
   - material_label (text, snapshot of material name at sale time)
   - quantity (numeric, volume/quantity sold)
   - unit (text, unit of measure for this sale)
   - unit_price (numeric, price per unit at sale time)
   - transport_fee (numeric, የማጓጓዣ ዋጋ, ETB)
   - subtotal (numeric, quantity * unit_price)
   - total (numeric, subtotal + transport_fee)
   - payment_method (text: cash | telebirr | cbe_bank | credit)
   - amount_paid (numeric, ETB paid at time of sale)
   - balance_due (numeric, total - amount_paid, non-zero for credit)
   - status (text: paid | partial | unpaid)
   - created_at (timestamptz)

4. `gate_passes` — truck dispatch records
   - id (uuid pk)
   - pass_number (text, unique, e.g. GP-000123)
   - sale_id (uuid, nullable FK to sales — a pass may be tied to a sale)
   - truck_plate (text, የመኪና ሰሌዳ)
   - driver_name (text)
   - destination (text, destination site)
   - material_label (text)
   - quantity (numeric)
   - unit (text)
   - order_ref (text, optional order/invoice reference)
   - dispatched_at (timestamptz, dispatch date/time)

5. `payments` — credit repayments applied to customer balances
   - id (uuid pk)
   - customer_id (uuid FK to customers)
   - sale_id (uuid, nullable FK to sales — can pay down a specific sale)
   - amount (numeric, ETB)
   - method (text: cash | telebirr | cbe_bank)
   - note (text, optional)
   - created_at (timestamptz)

## Security

Single-tenant, no auth: every policy is `TO anon, authenticated` with
`USING (true)` / `WITH CHECK (true)` because all data is intentionally shared
across the single operator using the system.

## Notes

- Stock is deducted by application code on sale insert (no DB trigger) to keep
  the flow transparent and debuggable.
- `invoice_number` and `pass_number` are generated by the app with a prefix and
  zero-padded running number.
*/

CREATE TABLE IF NOT EXISTS materials (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name_am text NOT NULL,
  name_en text NOT NULL,
  subtype text,
  unit text NOT NULL DEFAULT 'm³',
  unit_price numeric NOT NULL DEFAULT 0,
  stock_quantity numeric NOT NULL DEFAULT 0,
  low_stock_threshold numeric NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  phone text,
  credit_limit numeric NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sales (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invoice_number text UNIQUE NOT NULL,
  customer_name text NOT NULL,
  customer_id uuid REFERENCES customers(id) ON DELETE SET NULL,
  material_id uuid REFERENCES materials(id) ON DELETE SET NULL,
  material_label text NOT NULL,
  quantity numeric NOT NULL,
  unit text NOT NULL,
  unit_price numeric NOT NULL,
  transport_fee numeric NOT NULL DEFAULT 0,
  subtotal numeric NOT NULL,
  total numeric NOT NULL,
  payment_method text NOT NULL DEFAULT 'cash',
  amount_paid numeric NOT NULL DEFAULT 0,
  balance_due numeric NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'paid',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gate_passes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  pass_number text UNIQUE NOT NULL,
  sale_id uuid REFERENCES sales(id) ON DELETE SET NULL,
  truck_plate text NOT NULL,
  driver_name text NOT NULL,
  destination text NOT NULL,
  material_label text NOT NULL,
  quantity numeric NOT NULL,
  unit text NOT NULL,
  order_ref text,
  dispatched_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id uuid NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  sale_id uuid REFERENCES sales(id) ON DELETE SET NULL,
  amount numeric NOT NULL,
  method text NOT NULL DEFAULT 'cash',
  note text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sales_created_at_idx ON sales (created_at DESC);
CREATE INDEX IF NOT EXISTS sales_customer_id_idx ON sales (customer_id);
CREATE INDEX IF NOT EXISTS gate_passes_dispatched_at_idx ON gate_passes (dispatched_at DESC);
CREATE INDEX IF NOT EXISTS payments_customer_id_idx ON payments (customer_id);

